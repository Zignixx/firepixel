//! Writes `OUT_DIR/macros.rs`: for every enabled feature `<crate>` (e.g. `fp-ui`) the macro
//! `<crate_ident>!()` (e.g. `fp_ui!()`) with one module per integration test file of that crate.
//!
//! * `crates\<crate>\tests\<name>.rs` → `mod <name>;` (filter: `cargo test -p <crate> --test all <name>::`)
//! * helper folder `tests\<helper>\mod.rs` → `pub mod <helper>;`, compiled **once**; test files use
//!   it with `use crate::<helper>;` (a `mod <helper>;` inside a test file compiles a second copy
//!   with its own statics: cargo warning)
//! * left out: `tests\all.rs` and every file the crate's `Cargo.toml` lists as `[[test]]` of its
//!   own (`path = "tests/<name>.rs"`, tests that need a process of their own)
//!
//! The list lives in this separate crate on purpose: a build script of the test crate itself would
//! rerun on every test edit, and cargo then recompiles that crate's library as well.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};

fn main() {
    let manifest = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap_or_default());
    let crates = manifest.parent().map(Path::to_path_buf).unwrap_or_default();
    let mut out = String::from("// generated by crates/fp-testlist/build.rs (INF-1), do not edit\n\n");
    let mut features: Vec<String> = std::env::vars()
        .filter_map(|(k, _)| k.strip_prefix("CARGO_FEATURE_").map(|f| f.to_ascii_lowercase().replace('_', "-")))
        .collect();
    features.sort();
    for krate in features {
        let dir = crates.join(&krate);
        let tests = dir.join("tests");
        if !tests.is_dir() {
            println!("cargo:warning=fp-testlist: no folder {}", tests.display());
            continue;
        }
        println!("cargo:rerun-if-changed={}", tests.display());
        println!("cargo:rerun-if-changed={}", dir.join("Cargo.toml").display());
        let body = modules(&krate, &tests, &own_process_tests(&dir.join("Cargo.toml")));
        let _ = writeln!(out, "/// All integration test files of `{krate}` as modules (see `crates\\fp-testlist`).\n#[macro_export]\nmacro_rules! {} {{\n    () => {{\n{body}    }};\n}}\n", ident(&krate));
    }
    let dest = PathBuf::from(std::env::var("OUT_DIR").unwrap_or_default()).join("macros.rs");
    // only write on change: otherwise the test program would be rebuilt for nothing
    if std::fs::read_to_string(&dest).ok().as_deref() != Some(out.as_str())
        && let Err(e) = std::fs::write(&dest, out)
    {
        println!("cargo:warning=fp-testlist: macros.rs not written: {e}");
    }
}

fn modules(krate: &str, tests: &Path, own: &[String]) -> String {
    let mut helpers: Vec<(String, PathBuf)> = Vec::new();
    let mut files: Vec<(String, PathBuf)> = Vec::new();
    if let Ok(rd) = std::fs::read_dir(tests) {
        for e in rd.flatten() {
            let p = e.path();
            let name = e.file_name().to_string_lossy().to_string();
            if p.is_dir() {
                if p.join("mod.rs").is_file() {
                    helpers.push((ident(&name), p.join("mod.rs")));
                }
            } else if let Some(stem) = name.strip_suffix(".rs")
                && stem != "all"
                && !own.iter().any(|o| o == stem)
            {
                files.push((ident(stem), p));
            }
        }
    }
    helpers.sort();
    files.sort();
    let mut body = String::new();
    for (name, path) in &helpers {
        let _ = writeln!(body, "        #[macro_use]\n        #[allow(dead_code, unused_imports, unused_macros)]\n        #[path = {:?}]\n        pub mod {name};", path.display().to_string());
    }
    for (name, path) in &files {
        let _ = writeln!(body, "        #[path = {:?}]\n        mod {name};", path.display().to_string());
        if let Ok(src) = std::fs::read_to_string(path) {
            for (h, _) in &helpers {
                if declares_mod(&src, h) {
                    println!("cargo:warning={krate}/tests/{name}.rs: `mod {h};` compiles a second copy of the helper (own statics, own temp folders); write `use crate::{h};` (INF-1, docs\\AGENTEN_REGELN.md §2)");
                }
            }
        }
    }
    body
}

/// Stems of the files that `Cargo.toml` lists as `[[test]]` with `path = "tests/<stem>.rs"`.
fn own_process_tests(manifest: &Path) -> Vec<String> {
    let text = std::fs::read_to_string(manifest).unwrap_or_default();
    let mut out = Vec::new();
    let mut in_test = false;
    for line in text.lines() {
        let l = line.trim();
        if l.starts_with('[') {
            in_test = l == "[[test]]";
            continue;
        }
        let Some(v) = l.strip_prefix("path").map(str::trim_start).and_then(|r| r.strip_prefix('=')) else { continue };
        if !in_test {
            continue;
        }
        let v = v.trim().trim_matches('"').replace('\\', "/");
        if let Some(stem) = v.strip_prefix("tests/").and_then(|s| s.strip_suffix(".rs"))
            && !stem.contains('/')
        {
            out.push(stem.to_string());
        }
    }
    out
}

/// `mod <name>;` as an item on its own line (`pub mod` too).
fn declares_mod(src: &str, name: &str) -> bool {
    src.lines().any(|l| {
        let l = l.trim();
        let l = l.strip_prefix("pub ").unwrap_or(l);
        l.strip_prefix("mod ").and_then(|r| r.trim_end().strip_suffix(';')).is_some_and(|n| n.trim() == name)
    })
}

/// Valid Rust name for a file stem (`ux-a` → `ux_a`, `3d` → `t_3d`).
fn ident(stem: &str) -> String {
    let mut s: String = stem.chars().map(|c| if c.is_ascii_alphanumeric() || c == '_' { c } else { '_' }).collect();
    if s.chars().next().is_none_or(|c| c.is_ascii_digit()) {
        s.insert_str(0, "t_");
    }
    s
}
